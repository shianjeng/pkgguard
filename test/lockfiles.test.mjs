test('unreadable lockfiles say so instead of passing', async (t) => {
  const root = dir(t, { 'bun.lockb': 'binary\0data', 'package-lock.json': '{ not json' });
  assert.equal(lockedPackages(path.join(root, 'package-lock.json')), null);
  const sweeps = [await sweepLockfile(path.join(root, 'bun.lockb'), { fetchImpl: fakeFetch() })];
  const { results, notes } = sweepReport(sweeps, root);
  assert.equal(results.length, 0);
  assert.match(notes[0].text, /bun\.lockb could not be read.*bun install --save-text-lockfile/);
});

test('a malicious transitive version blocks; vulnerabilities are only counted', async (t) => {
  const root = dir(t, {
    'package-lock.json': {
      lockfileVersion: 3,
      packages: {
        '': {},
        'node_modules/express': { version: '5.3.0', resolved: 'https://registry.npmjs.org/express/-/express-5.3.0.tgz' },
        'node_modules/debug': { version: '4.4.2', resolved: 'https://registry.npmjs.org/debug/-/debug-4.4.2.tgz' },
        'node_modules/lodash': { version: '4.17.20', resolved: 'https://registry.npmjs.org/lodash/-/lodash-4.17.20.tgz' },
      },
    },
  });
  const fetchImpl = fakeFetch();
  const sweep = await sweepLockfile(path.join(root, 'package-lock.json'), { fetchImpl });
  assert.equal(fetchImpl.calls.length, 1, 'one batch request for the whole lockfile');
  assert.equal(sweep.total, 3);
  assert.deepEqual(sweep.malicious, [{ ecosystem: 'npm', name: 'debug', version: '4.4.2', ids: ['MAL-2025-46974'] }]);
  assert.equal(sweep.vulnerable, 1);

  const { results, notes } = sweepReport([sweep], root, { mentionVulnerable: true });
  assert.equal(results[0].verdict, 'block');
  assert.match(results[0].findings[0].text, /package-lock\.json pins debug@4\.4\.2, which is reported as malicious \(MAL-2025-46974\)/);
  assert.match(notes[0].text, /known vulnerabilities for 1 of the packages in package-lock\.json; npm audit shows which/);
  assert.match(renderResults(results, { notes }), /✗ BLOCK debug@4\.4\.2 \(npm\) · from package-lock\.json/);
});

test('a clean lockfile is one note, and OSV being down is a warning', async (t) => {
  const root = dir(t, { 'package-lock.json': { packages: { 'node_modules/express': { version: '5.3.0' } } } });
  const file = path.join(root, 'package-lock.json');
  const clean = sweepReport([await sweepLockfile(file, { fetchImpl: fakeFetch() })], root);
  assert.deepEqual(clean.results, []);
  assert.deepEqual(clean.notes, [{ level: 'info', text: 'The 1 package pinned in package-lock.json was checked against OSV malware reports: none reported.' }]);

  const down = fakeFetch({ 'api.osv.dev': () => new Response('unavailable', { status: 503 }) });
  const offline = sweepReport([await sweepLockfile(file, { fetchImpl: down })], root);
  assert.equal(offline.notes[0].level, 'warn');
  assert.match(offline.notes[0].text, /Could not check the 1 packages pinned in package-lock\.json against OSV malware reports \(api\.osv\.dev answered 503\)/);
});

test('large lockfiles are sent in batches of a thousand', async (t) => {
  const packages = { '': {} };
  for (let i = 0; i < 2500; i++) packages[`node_modules/pkg-${i}`] = { version: '1.0.0' };
  const root = dir(t, { 'package-lock.json': { packages } });
  const fetchImpl = fakeFetch();
  const sweep = await sweepLockfile(path.join(root, 'package-lock.json'), { fetchImpl });
  assert.equal(sweep.total, 2500);
  assert.equal(fetchImpl.calls.length, 3);
});

function runHook(input) {
  return new Promise((resolve) => {
    const child = execFile(
      process.execPath,
      ['--import', path.join(ROOT, 'test/fixtures/install-fake-fetch.mjs'), path.join(ROOT, 'skills/pkgguard/scripts/hook.mjs')],
      { env: { ...process.env, PKGGUARD_NO_CACHE: '1' } },
      (err, stdout, stderr) => resolve({ code: err?.code ?? 0, stdout, stderr }),
    );
    child.stdin.end(JSON.stringify(input));
  });
}

test('hook: npm ci from a lockfile that pins a hijacked transitive version is denied', async (t) => {
  const root = dir(t, {
    'app/package.json': { dependencies: { express: '^5.0.0' } },
    'app/package-lock.json': {
      lockfileVersion: 3,
      packages: {
        '': { dependencies: { express: '^5.0.0' } },
        'node_modules/express': { version: '5.3.0', resolved: 'https://registry.npmjs.org/express/-/express-5.3.0.tgz' },
        'node_modules/debug': { version: '4.4.2', resolved: 'https://registry.npmjs.org/debug/-/debug-4.4.2.tgz' },
      },
    },
  });
  const { stdout } = await runHook({ tool_name: 'Bash', tool_input: { command: 'cd app && npm ci' }, cwd: root });
  const out = JSON.parse(stdout).hookSpecificOutput;
  assert.equal(out.permissionDecision, 'deny');
  assert.match(out.permissionDecisionReason, /app\/package-lock\.json pins debug@4\.4\.2/);
});

test('hook: npm ci from a clean lockfile stays silent', async (t) => {
  const root = dir(t, {
    'package.json': { dependencies: { express: '^5.0.0' } },
    'package-lock.json': { lockfileVersion: 3, packages: { '': {}, 'node_modules/express': { version: '5.3.0' } } },
  });
  assert.deepEqual(await runHook({ tool_name: 'Bash', tool_input: { command: 'npm ci' }, cwd: root }), { code: 0, stdout: '', stderr: '' });
});
